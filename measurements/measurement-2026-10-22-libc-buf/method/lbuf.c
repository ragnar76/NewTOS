/*
 * lbuf.c -- TASK/LIBC-BUF probe, C:\AUTO\LBUF.NCP (one binary, role by argv[1]).
 *
 * Question: does a stdout that the parent redirected to a file (Fforce before
 * the spawn, so the child's main.c sees isatty(1) == 0) keep a 32 KiB stdio
 * buffer after its first printf, as a fopen() file does (FS08 part 4)? And is
 * the console stdout unchanged (printf without a newline is written at once
 * while stdout has no buffer, line buffered once one exists)?
 *
 * All reporting goes through Bconout(2) (BIOS CON), never through stdio and
 * never through Cconws: Cconws follows a redirected handle 1
 * (tos-api/src/gemdos/console.rs redirected_std), so it would land in the file.
 *
 *   (none) PARENT:
 *     C   spawn kid "c" with nothing redirected (console control).
 *     O   Fcreate C:\LBO.TXT, Fforce(1, fh), spawn kid "o", Fforce(1, -1),
 *         Fclose, re-read: content must be exactly what the kid printed
 *         (text mode: "\n" -> "\r\n").
 *     F1  fopen + fprintf first (control: 0x8000, buffer).
 *     F2  fopen + fileno() first, then fprintf (same class as stdout: the
 *         stream is "seen" before its first output, no buffer yet).
 *     F3  fopen + setvbuf(_IONBF) + fprintf (unbuffered by request: stays so).
 *   "c" / "o" KID: traces stdout's stdio fields (seen, buffer, bufsize,
 *     pending = bytes in the buffer not yet written, linebuf, userbuf) around
 *     its printf / putchar calls; checks; exits with its failure count.
 * Verdict lines "LBUF[..] ok/FAIL"; last line "LBUF: PASS" or "LBUF: FAIL n".
 */
#include <mint/osbind.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <process.h>

#define SELF "C:\\AUTO\\LBUF.NCP"
#define NLINES 2000

static int fails;

static void con(const char *s)
{
	while (*s)
		Bconout(2, (unsigned char)*s++);
}

static void puthex(unsigned long v)
{
	static const char d[] = "0123456789abcdef";
	char b[11];
	int i;
	b[0] = '0';
	b[1] = 'x';
	for (i = 0; i < 8; i++)
		b[2 + i] = d[(v >> ((7 - i) * 4)) & 0xf];
	b[10] = '\0';
	con(b);
}

static void kv(const char *k, unsigned long v)
{
	con(" "); con(k); con("="); puthex(v);
}

static void check(const char *role, const char *what, int ok)
{
	con("LBUF["); con(role); con("] "); con(ok ? "ok   " : "FAIL "); con(what); con("\r\n");
	if (!ok)
		fails++;
}

static unsigned long pending(FILE *f)
{
	return f->__buffer ? (unsigned long)(f->__bufp - f->__buffer) : 0UL;
}

static void trace(const char *role, const char *name, const char *when, FILE *f)
{
	con("LBUF["); con(role); con("] "); con(name); con(" "); con(when);
	kv("seen", (unsigned long)f->__seen);
	kv("buffer", f->__buffer ? 1UL : 0UL);
	kv("bufsize", (unsigned long)f->__bufsize);
	kv("pending", pending(f));
	kv("linebuf", (unsigned long)f->__linebuf);
	kv("userbuf", (unsigned long)f->__userbuf);
	con("\r\n");
}

/* The kid "o" output, also regenerated by the parent for the comparison. */
static const char *o_line(int i, char *b)
{
	static const char d[] = "0123456789";
	memcpy(b, "L0000 abcdefghij\n", 18);
	b[1] = d[(i / 1000) % 10];
	b[2] = d[(i / 100) % 10];
	b[3] = d[(i / 10) % 10];
	b[4] = d[i % 10];
	return b;
}

static int kid_o(void)
{
	char b[20];
	int i;

	trace("o", "stdout", "before printf", stdout);
	check("o", "before: bufsize 0x8000, no buffer, not line buffered",
	      stdout->__bufsize == 0x8000 && !stdout->__buffer && !stdout->__linebuf && !stdout->__userbuf);

	printf("o line %d\n", 1);                 /* 9 bytes in the buffer */
	trace("o", "stdout", "after first printf", stdout);
	check("o", "after first printf: buffer, bufsize 0x8000, 9 bytes pending (held, not written)",
	      stdout->__buffer && stdout->__bufsize == 0x8000 && pending(stdout) == 9);

	putchar('x');
	trace("o", "stdout", "after putchar", stdout);
	check("o", "after putchar: bufsize 0x8000, 10 bytes pending",
	      stdout->__buffer && stdout->__bufsize == 0x8000 && pending(stdout) == 10);

	for (i = 0; i < NLINES; i++)
		printf("%s", o_line(i, b));
	trace("o", "stdout", "after 2000 printf", stdout);
	check("o", "after 2000 printf (34010 bytes > 32 KiB): bufsize still 0x8000",
	      stdout->__buffer && stdout->__bufsize == 0x8000);

	fprintf(stderr, "LBUF[o] stderr line\r\n");
	trace("o", "stderr", "after fprintf", stderr);
	check("o", "stderr unbuffered by request (no buffer, userbuf 1)", !stderr->__buffer && stderr->__userbuf);

	con("LBUF[o]: DONE"); kv("fails", (unsigned long)fails); con("\r\n");
	return fails;                             /* exit() flushes stdout */
}

static int kid_c(void)
{
	trace("c", "stdout", "before printf", stdout);
	check("c", "before: bufsize 0x400, no buffer, line buffered",
	      stdout->__bufsize == 0x400 && !stdout->__buffer && stdout->__linebuf);

	printf("<c printf no newline>");          /* must appear BEFORE the next trace line */
	trace("c", "stdout", "after printf", stdout);
	check("c", "after printf: still no buffer (written at once)", !stdout->__buffer && pending(stdout) == 0);

	putchar('\r');
	putchar('\n');
	trace("c", "stdout", "after putchar CR LF", stdout);
	check("c", "after putchar: line buffer, 0 pending (newline flushed)",
	      stdout->__buffer && stdout->__linebuf && pending(stdout) == 0);

	printf("<c second printf no newline>");
	trace("c", "stdout", "after second printf", stdout);
	check("c", "after second printf: held in the line buffer (28 pending)",
	      stdout->__buffer && pending(stdout) == 28);
	printf("\r\n");

	con("LBUF[c]: DONE"); kv("fails", (unsigned long)fails); con("\r\n");
	return fails;
}

static void parent_o(void)
{
	static char got[40000];
	char want[40000], b[20];
	long fh, f, r, n, h, wn = 0, i, j;
	int ok;

	Fdelete("C:\\LBO.TXT");
	fh = Fcreate("C:\\LBO.TXT", 0);
	f = Fforce(1, (short)fh);
	con("LBUF[PAR] O"); kv("Fcreate", (unsigned long)fh); kv("Fforce(1)", (unsigned long)f); con("\r\n");
	r = spawnl(P_WAIT, SELF, "LBUF", "o", (char *)NULL);
	f = Fforce(1, -1);
	con("LBUF[PAR] O spawn o"); kv("rc", (unsigned long)r); kv("Fforce(1,-1)", (unsigned long)f);
	kv("Fclose", (unsigned long)Fclose((short)fh)); con("\r\n");
	check("PAR", "O kid o rc 0", r == 0);

	memcpy(want, "o line 1\r\nx", 11);
	wn = 11;
	for (i = 0; i < NLINES; i++) {
		o_line((int)i, b);
		for (j = 0; b[j]; j++) {
			if (b[j] == '\n')
				want[wn++] = '\r';
			want[wn++] = b[j];
		}
	}
	h = Fopen("C:\\LBO.TXT", 0);
	n = h < 0 ? h : Fread((short)h, sizeof got, got);
	if (h >= 0)
		Fclose((short)h);
	ok = n == wn && memcmp(got, want, (size_t)wn) == 0;
	con("LBUF[PAR] O LBO.TXT"); kv("len", (unsigned long)n); kv("want", (unsigned long)wn); con("\r\n");
	check("PAR", "O LBO.TXT = exactly the kid's output (text mode)", ok);
}

static void parent_f(void)
{
	FILE *f;

	f = fopen("C:\\LBF1.TXT", "w");
	if (!f) { check("PAR", "F1 fopen", 0); return; }
	fprintf(f, "f%d\n", 1);
	trace("PAR", "F1", "after first fprintf", f);
	check("PAR", "F1 fopen+fprintf: buffer, bufsize 0x8000, 3 pending",
	      f->__buffer && f->__bufsize == 0x8000 && pending(f) == 3);
	fclose(f);

	f = fopen("C:\\LBF2.TXT", "w");
	if (!f) { check("PAR", "F2 fopen", 0); return; }
	(void)fileno(f);
	trace("PAR", "F2", "after fileno", f);
	fprintf(f, "f%d\n", 2);
	trace("PAR", "F2", "after first fprintf", f);
	check("PAR", "F2 fopen+fileno+fprintf: buffer, bufsize 0x8000, 3 pending",
	      f->__buffer && f->__bufsize == 0x8000 && pending(f) == 3);
	fclose(f);

	f = fopen("C:\\LBF3.TXT", "w");
	if (!f) { check("PAR", "F3 fopen", 0); return; }
	setvbuf(f, NULL, _IONBF, 0);
	fprintf(f, "f%d\n", 3);
	trace("PAR", "F3", "after fprintf", f);
	check("PAR", "F3 _IONBF: stays without buffer", !f->__buffer && f->__userbuf);
	fclose(f);
}

int main(int argc, char **argv)
{
	long r;

	if (argc > 1)
		return argv[1][0] == 'o' ? kid_o() : kid_c();

	con("LBUF[PAR] start\r\n");
	r = spawnl(P_WAIT, SELF, "LBUF", "c", (char *)NULL);
	con("LBUF[PAR] C spawn c"); kv("rc", (unsigned long)r); con("\r\n");
	check("PAR", "C kid c rc 0", r == 0);
	parent_o();
	parent_f();
	if (fails) {
		con("LBUF: FAIL "); puthex((unsigned long)fails); con("\r\n");
	} else
		con("LBUF: PASS\r\n");
	return 0;
}
