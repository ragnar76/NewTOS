#!/usr/bin/env python3
"""apply-injector-m3.py <scratch-tree> <script.rs>

Scratch-only input source for the TASK/LDG-M3 interactive runs (QEMU raspi4b
has no USB keyboard/mouse and the rpi4 profile drops serial RX). NEVER applied
to the shared tree. Recipe: the H02/GUI04 scripted IKBD injector
(measurement-2026-10-01-desk50/method/apply_injector.py), hooked in at the
three usb::poll() sites of host_env.rs like
measurement-2026-10-05-arch03-0c/method/apply-instrumentation.py (pump_input
and both blocking read loops). It adds ONLY an input source; the kernel code
under test is the shared tree's.

The clock starts at the first poll that sees an EL0 program running (RUN not
null) -- on the M3 cards the first EL0 program is the #Z-launched LDGDEMO.NAP
(no accessories, no AUTO folder). SCRIPT (generated by gen_script.py) is a list
of (ticks after arming, step); `Mark` prints "[m3] MARK <name>" on the serial
line, which drive-m3.py turns into a screendump.
"""
import sys, pathlib
t = pathlib.Path(sys.argv[1])
script_rs = pathlib.Path(sys.argv[2]).read_text()
he = t / "kernel/src/host_env.rs"
s = he.read_text()
anchor = "crate::drivers::usb::poll();\n"
n = s.count(anchor)
assert n == 3, f"host_env.rs: expected 3 usb::poll sites, found {n}"
s = s.replace(anchor, "crate::drivers::usb::poll();\n        #[cfg(feature = \"board-rpi4\")] m3_inject::step(); // M3-TEMP\n")
s += '''
// M3-TEMP BEGIN -- scripted IKBD mouse/keys (QEMU raspi4b has no input path)
#[cfg(feature = "board-rpi4")]
pub mod m3_inject {
    use core::sync::atomic::{AtomicU32, AtomicUsize, Ordering};
    static T0: AtomicU32 = AtomicU32::new(0);
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    #[allow(dead_code)]
    #[derive(Clone, Copy)]
    pub enum Step { Mv(i8, i8), Dm(i8, i8), Dn, Up, Arm, Mark(&'static str), Pause, Key(u8), Wheel(i8, usize) }

''' + script_rs + '''
    pub fn step() {
        if tos_api::bdos::process::RUN.load(Ordering::Acquire).is_null() && T0.load(Ordering::Relaxed) == 0 {
            return; // the clock starts with the first EL0 program
        }
        let now = tos_api::bios::tick::hz_200();
        if T0.load(Ordering::Relaxed) == 0 {
            T0.store(now.max(1), Ordering::Relaxed);
            crate::kprintln!("[m3] injector armed at hz_200 {}", now);
            return;
        }
        let t0 = T0.load(Ordering::Relaxed);
        let i = NEXT.load(Ordering::Relaxed);
        if i >= SCRIPT.len() {
            return;
        }
        let (at, st) = SCRIPT[i];
        if now.wrapping_sub(t0) < at {
            return;
        }
        match st {
            Step::Mv(dx, dy) => { for b in [0xF8u8, dx as u8, dy as u8] { crate::ikbd::feed(b); } }
            Step::Dm(dx, dy) => { for b in [0xFAu8, dx as u8, dy as u8] { crate::ikbd::feed(b); } }
            Step::Dn => { for b in [0xFAu8, 0, 0] { crate::ikbd::feed(b); } }
            Step::Up => { for b in [0xF8u8, 0, 0] { crate::ikbd::feed(b); } }
            Step::Key(b) => { crate::ikbd::feed(b); }
            Step::Arm | Step::Pause | Step::Mark(_) | Step::Wheel(..) => {}
        }
        let (mx, my) = tos_api::vdi::mouse_position();
        let mb = tos_api::vdi::mouse_buttons();
        match st {
            Step::Mark(name) => crate::kprintln!("[m3] MARK {} step {} at +{} mouse ({},{}) mb={}", name, i, now.wrapping_sub(t0), mx, my, mb),
            _ => crate::kprintln!("[m3] step {} at +{} -> mouse ({},{}) mb={}", i, now.wrapping_sub(t0), mx, my, mb),
        }
        NEXT.store(i + 1, Ordering::Relaxed);
    }
}
// M3-TEMP END
'''
he.write_text(s)
print("instrumented", he)
