#!/usr/bin/env python3
"""expected.py <ldbl-oracle.py> <ldbl-host> <LDBL-x18.elf> -> expected.h (stdout) + expected.txt (stderr)

Expected values of the QEMU probe ldp.c (TASK/SDK01 J), from the oracle of the
host test (sdk/libc/tests/ldbl-oracle.py: exact rational arithmetic):
  - printf/strtold/sscanf/qecvt/qfcvt/qgcvt/1/3: exact
    values, computed here;
  - the five transcendental l functions (expl, logl, sinl, powl, cbrtl): the
    bit pattern the host run of the same machine code gives (ldbl-host on the
    -ffixed-x18 rebuild that ldbl-host.sh links; it proves the rebuild
    byte-identical to the shipped members apart from the register reserve),
    with its ulp distance to a 130-digit reference written to expected.txt.
"""
import importlib.util
import subprocess
import sys
from fractions import Fraction as F

spec = importlib.util.spec_from_file_location("o", sys.argv[1])
o = importlib.util.module_from_spec(spec)
spec.loader.exec_module(o)
host, elf = sys.argv[2], sys.argv[3]


def h(b):
    return "0x%016xULL, 0x%016xULL" % (b >> 64, b & ((1 << 64) - 1))


third = o.q_from(F(1, 3))
out = []
txt = []
def S(name, val):
    out.append('#define %s "%s"' % (name, val.replace("\\", "\\\\").replace('"', '\\"')))
    txt.append("%-14s %s" % (name, val))
def Q(name, b):
    out.append("#define %s %s" % (name, h(b)))
    txt.append("%-14s %s" % (name, o.q_hex(b)))

S("E_P35E_THIRD", o.fmt_e(third, 35))
S("E_PLA_THIRD", o.fmt_a(third))
S("E_PLF_THIRD", o.fmt_f(third, 6))
S("E_PLG_1E4000", o.fmt_g(o.q_from(F(10) ** 4000), 6))
maxq = ((o.EMAX - 1) << o.FB) | ((1 << o.FB) - 1)
S("E_P20E_MAX", o.fmt_e(maxq, 20))
S("E_P20E_DMIN", o.fmt_e(1, 20))
S("E_PLA_DMIN", o.fmt_a(1))
S("E_P40F_TWO3", o.fmt_f(o.q_from(F(2, 3)), 40))
Q("E_STRTOLD_01", o.q_from(F(1, 10)))
Q("E_STRTOLD_SUB", o.q_from(F(1, 10) ** 4950))
Q("E_STRTOLD_MAX", maxq)
Q("E_SSCANF_PI", o.q_from(o.parse_dec("3.14159265358979323846264338327950288")))
# qecvt(1/3, 10), qfcvt(2.5, 3), qgcvt(0.125, 6) -- SDK01 E's INFO cases
S("E_QECVT", "3333333333")
S("E_QFCVT", "2500")
S("E_QGCVT", "0.125")
# 1/3 rounded to nearest (the probe's fenv checks use an addition: 1 +- 2^-200)
Q("E_THIRD", third)
# libm transcendental: host run of the same code
req = ["expl\t%s" % o.q_hex(o.q_from(F(1))),
       "logl\t%s" % o.q_hex(o.q_from(F(2))),
       "sinl\t%s" % o.q_hex(o.q_from(F(1))),
       "powl\t%s\t%s" % (o.q_hex(o.q_from(F(2))), o.q_hex(o.q_from(F(1, 2)))),
       "cbrtl\t%s" % o.q_hex(o.q_from(F(2)))]
p = subprocess.run([host, elf], input="".join(r + "\n" for r in req), capture_output=True, text=True, check=True)
for r, rep, name, fn, args in zip(req, p.stdout.split("\n"), ("E_EXPL1", "E_LOGL2", "E_SINL1", "E_POWL", "E_CBRTL2"),
                                  ("expl", "logl", "sinl", "powl", "cbrtl"),
                                  ([F(1)], [F(2)], [F(1)], [F(2), F(1, 2)], [F(2)])):
    b = o.q_parse(rep)
    Q(name, b)
    ref = o.fd(o.ref(fn, args))
    txt.append("   %s: %.3f ulp from the 130-digit reference (correctly rounded: %s)"
               % (fn, float(abs(o.q_val(b) - ref) / o.ulp_of(ref)), o.q_hex(o.q_from(ref))))
print("/* generated by expected.py -- do not edit */")
print("\n".join(out))
sys.stderr.write("\n".join(txt) + "\n")
