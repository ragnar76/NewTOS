#!/usr/bin/env python3
"""gen.py <spec> > <script> -- turn a high-level DESK48 injector spec into a tools/inject-arm.py script.

Spec lines (one action each, '#' comments):
  park                 mouse to (0, bottom) -- 6 x (-128,+127) packets; position becomes (0,479)
  wait <ticks>         advance the clock (200 Hz)
  move <x> <y>         absolute move (buttons up) from the tracked position, split into |d|<=127 packets
  click                left press + release
  dclick               two clicks 10 ticks apart
  press / release      left button down / up
  drag <x> <y>         move with the left button held, in steps of <= 12 px (as the desk62 scripts)
  key <b> [<b> ...]    raw IKBD bytes (make/break scancodes)
  mark <name>          no input; writes "<name> <bytes fed so far>" to stderr -- the N for an mdrive.py
                       'feed@N' screendump step (the injector logs one feed line per byte)
Each action is emitted at the current clock, which then advances by a small gap (10 ticks, drag steps 20, press 50)."""
import sys
t = 200; x, y = 0, 479; out = []
def emit(*b):
    global t
    out.append("%d %s" % (t, " ".join("0x%02X" % (v & 0xFF) for v in b)))
def rel(dx, dy, btn):
    pk = []
    while dx or dy:
        sx = max(-128, min(127, dx)); sy = max(-128, min(127, dy))
        pk += [0xF8 | btn, sx, sy]; dx -= sx; dy -= sy
    return pk
def nbytes():
    return sum(len(l.split()) - 1 for l in out)
for line in open(sys.argv[1]):
    line = line.split('#')[0].split()
    if not line: continue
    op, a = line[0], line[1:]
    if op == 'park':
        emit(*([0xF8, 0x80, 0x7F] * 6)); x, y = 0, 479; t += 20
    elif op == 'wait':
        t += int(a[0])
    elif op == 'move':
        nx, ny = int(a[0]), int(a[1]); pk = rel(nx - x, ny - y, 0)
        if pk: emit(*pk); t += 20
        x, y = nx, ny
    elif op == 'click':
        emit(0xFA, 0, 0); t += 10; emit(0xF8, 0, 0); t += 20
    elif op == 'dclick':
        emit(0xFA, 0, 0); t += 5; emit(0xF8, 0, 0); t += 10; emit(0xFA, 0, 0); t += 5; emit(0xF8, 0, 0); t += 20
    elif op == 'press':
        emit(0xFA, 0, 0); t += 50
    elif op == 'release':
        emit(0xF8, 0, 0); t += 20
    elif op == 'drag':
        nx, ny = int(a[0]), int(a[1])
        while (x, y) != (nx, ny):
            sx = max(-12, min(12, nx - x)); sy = max(-12, min(12, ny - y))
            emit(0xFA, sx, sy); x += sx; y += sy; t += 20
        t += 20
    elif op == 'mark':
        sys.stderr.write("%s %d\n" % (a[0], nbytes()))
    elif op == 'key':
        emit(*[int(v, 0) for v in a]); t += 20
    else:
        sys.exit("bad op " + op)
print("# generated by gen.py from " + sys.argv[1])
print("\n".join(out))
