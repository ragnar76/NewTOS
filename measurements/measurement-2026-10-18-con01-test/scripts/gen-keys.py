#!/usr/bin/env python3
"""gen-keys.py <out.script> <start-tick> <spec...> -- IKBD scancode script for tools/inject-arm.py (200 Hz ticks, 8 ticks between
make/break edges, 32 ticks per key). spec tokens: k:<hexmake> plain key, l:<hex> with LShift, r:<hex> with RShift, b:<hex> with both Shifts,
c:<hex> with Ctrl, ca:<hex> with Ctrl+Alt, w:<ticks> wait. e.g. l:0x23 = 'H' (German layout scancode set)."""
import sys
out = sys.argv[1]; t = int(sys.argv[2]); L = []
def e(*b):
    global t
    for x in b: L.append("%d 0x%02X" % (t, x)); t += 8
for tok in sys.argv[3:]:
    k, v = tok.split(":"); v = int(v, 0)
    if k == "w": t += v; continue
    pre = {"k": [], "l": [0x2A], "r": [0x36], "b": [0x2A, 0x36], "c": [0x1D], "ca": [0x1D, 0x38]}[k]
    for p in pre: e(p)
    e(v, v | 0x80)
    for p in reversed(pre): e(p | 0x80)
    t += 24
open(out, "w").write("# generated by gen-keys.py %s\n" % " ".join(sys.argv[2:]) + "\n".join(L) + "\n")
print(out, len(L), "events, last tick", t)
