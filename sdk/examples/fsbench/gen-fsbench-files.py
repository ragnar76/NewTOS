#!/usr/bin/env python3
"""gen-fsbench-files.py -- the FSBENCH test file set (TASK/FS08).

Writes the ten read-only test files FSBENCH.NCP expects in D:\\FSBENCH\\,
plus MANIFEST.TXT (name, size, CRC-32) and SHA256SUMS, and regenerates the
C header fsbench-manifest.h that FSBENCH.NCP embeds, so the program verifies
every read against the same numbers without needing the manifest on the card.

    3 x 10 KiB, 3 x 100 KiB, 2 x 1 MiB, 2 x 10 MiB   (sizes are exact KiB/MiB)

Content is deterministic and incompressible: byte stream =
SHA-256(b"FSBENCH" + name + 8-byte little-endian block index), concatenated,
truncated to the size. Same output on every host and every Python version.
CRC-32 is the IEEE/zlib polynomial (zlib.crc32), the one FSBENCH computes.

Usage:
    gen-fsbench-files.py OUTDIR [--header PATH]
      OUTDIR    receives the ten files + MANIFEST.TXT + SHA256SUMS
      --header  where to write fsbench-manifest.h
                (default: next to this script)
"""
import argparse
import hashlib
import os
import struct
import sys
import zlib

KIB = 1024
MIB = 1024 * KIB

# (8.3 name, size). Order = the order FSBENCH measures in.
FILES = [
    ("K010_1.DAT", 10 * KIB),
    ("K010_2.DAT", 10 * KIB),
    ("K010_3.DAT", 10 * KIB),
    ("K100_1.DAT", 100 * KIB),
    ("K100_2.DAT", 100 * KIB),
    ("K100_3.DAT", 100 * KIB),
    ("M001_1.DAT", 1 * MIB),
    ("M001_2.DAT", 1 * MIB),
    ("M010_1.DAT", 10 * MIB),
    ("M010_2.DAT", 10 * MIB),
]


def content(name, size):
    out = bytearray()
    i = 0
    seed = b"FSBENCH" + name.encode("ascii")
    while len(out) < size:
        out += hashlib.sha256(seed + struct.pack("<Q", i)).digest()
        i += 1
    return bytes(out[:size])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--header", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "fsbench-manifest.h"))
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)

    rows = []
    for name, size in FILES:
        data = content(name, size)
        crc = zlib.crc32(data) & 0xFFFFFFFF
        sha = hashlib.sha256(data).hexdigest()
        with open(os.path.join(a.outdir, name), "wb") as f:
            f.write(data)
        rows.append((name, size, crc, sha))
        print(f"{name}  {size:9d}  crc32 {crc:08x}")

    with open(os.path.join(a.outdir, "MANIFEST.TXT"), "w", newline="\r\n") as f:
        f.write("FSBENCH test files (TASK/FS08) -> D:\\FSBENCH\\\n")
        f.write("name        size  crc32\n")
        for name, size, crc, _ in rows:
            f.write(f"{name:<10} {size:9d}  {crc:08x}\n")
    with open(os.path.join(a.outdir, "SHA256SUMS"), "w") as f:
        for name, _, _, sha in rows:
            f.write(f"{sha}  {name}\n")

    with open(a.header, "w") as f:
        f.write("/* fsbench-manifest.h -- GENERATED by gen-fsbench-files.py, do not edit.\n"
                " * The FSBENCH test file set: 8.3 name, exact size, CRC-32 (IEEE/zlib). */\n")
        f.write("static const struct fsb_file {\n\tconst char *name;\n"
                "\tlong size;\n\tunsigned int crc;\n} fsb_files[] = {\n")
        for name, size, crc, _ in rows:
            f.write(f'\t{{ "{name}", {size}L, 0x{crc:08x}u }},\n')
        f.write("};\n#define FSB_NFILES ((int)(sizeof fsb_files / sizeof fsb_files[0]))\n")
    print(f"wrote {a.outdir}/MANIFEST.TXT, SHA256SUMS, {a.header}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
