//! VDI fill-pattern ROM tables and active-pattern selection.
//!
//! Source: EmuTOS @ `1a7484ab` — `vdi/vdi_fill.c` (`OEMPAT`/`DITHER`/
//! `HATCH0`/`HATCH1`, `st_fl_ptr`). A pattern is a run of 16-bit rows;
//! scanline `y` uses row `pattern[y & (len-1)]`, pixel `x` uses bit
//! `0x8000 >> (x & 0xF)`. Patterns are screen-aligned (absolute `x`/`y`).

use super::vwk::Vwk;

// Interior styles (`vdi_defs.h`).
