#!/usr/bin/env python3
"""Generate the H02 injector SCRIPT (Rust) from a high-level action list.

usage: gen_script.py ACTIONS.txt > script.rs
ACTIONS lines:  <tick> park | <tick> move X Y | <tick> down | <tick> up | <tick> arm | <tick> mark NAME | <tick> pause
Absolute coordinates on the 640x480 screen; the generator tracks the pointer
and emits IKBD relative packets (|d| <= 127 per packet, one packet per tick).
"""
import sys
acts=[l.split() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
px=py=None
out=[]
def emit(t, kind, dx=0, dy=0, name=""):
    out.append((t,kind,dx,dy,name))
for a in acts:
    t=int(a[0]); op=a[1]
    if op=='park':
        for k in range(6): emit(t+k,'mv',-127,-127)
        px=py=0
    elif op=='parkbl':
        # A73: park in the BOTTOM-left corner (0,479): the sweep from the
        # screen centre never crosses the menu bar row, so no drop-down can
        # latch on the way (H02 verify: the (0,0) park sits in the bar).
        for k in range(6): emit(t+k,'mv',-127,127)
        px,py=0,479
    elif op=='move':
        x,y=int(a[2]),int(a[3]); dx,dy=x-px,y-py
        k=0
        while dx or dy:
            sx=max(-127,min(127,dx)); sy=max(-127,min(127,dy))
            emit(t+k,'mv',sx,sy); dx-=sx; dy-=sy; k+=1
        px,py=x,y
    elif op=='drag':
        x,y=int(a[2]),int(a[3]); dx,dy=x-px,y-py
        k=0
        while dx or dy:
            sx=max(-127,min(127,dx)); sy=max(-127,min(127,dy))
            emit(t+k,'dm',sx,sy); dx-=sx; dy-=sy; k+=1
        px,py=x,y
    elif op=='down': emit(t,'dn')
    elif op=='up': emit(t,'up')
    elif op=='arm': emit(t,'arm')
    elif op=='mark': emit(t,'mark',name=a[2])
    elif op=='pause': emit(t,'pause')
print("    // generated by gen_script.py from", sys.argv[1])
print("    const " + (sys.argv[2] if len(sys.argv)>2 else "SCRIPT") + ": &[(u32, Step)] = &[")
for t,kind,dx,dy,name in out:
    if kind=='mv': print(f"        ({t}, Step::Mv({dx}, {dy})),")
    elif kind=='dm': print(f"        ({t}, Step::Dm({dx}, {dy})),")
    elif kind=='dn': print(f"        ({t}, Step::Dn),")
    elif kind=='up': print(f"        ({t}, Step::Up),")
    elif kind=='arm': print(f"        ({t}, Step::Arm),")
    elif kind=='mark': print(f"        ({t}, Step::Mark(\"{name}\")),")
    elif kind=='pause': print(f"        ({t}, Step::Pause),")
print("    ];")
