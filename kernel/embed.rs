//! The programs the kernel image carries — DESK43 decision D3 (load form E of
//! `docs/analysis/desk43-u5-u10-review-2026-10-14.md` §5): the desktop
//! program is built by `cargo xtask build-programs` and **embedded in the
//! kernel image**, registered under its registry name, as EmuTOS' desktop
//! lies in the ROM (`aes_run_rom_program(deskstart)`, `aes/gemshlib.c:606`).
//! The kernel build depends on the program build and stops with a hard error
//! when a blob is missing; there is one blob per board (the X03 board feature
//! is passed through to the program build).
//!
//! This file is the build-time half, shared by two users and therefore free of
//! anything but `std`:
//!
//! * `kernel/build.rs` includes it (`mod embed`) and turns [`EMBEDDED`] into
//!   `$OUT_DIR/embedded_programs.rs` with [`generate`] — or fails the build;
//! * `tools/xtask` includes it by path for its host tests (the kernel crate
//!   cannot be built for the host), which pin the hard error and the
//!   generated source.
//!
//! The run-time half is `kernel/src/embedded.rs` (registration at boot).
//!
//! **State at DESK43 U6b: the list is empty.** The mechanism is complete —
//! board directory, hard error, generated `include_bytes!`, registration — but
//! the desktop program it is for does not exist before U9, and nothing else
//! belongs in the image (a test program embedded here would also shadow a
//! card file of the same name, `registry::lookup` runs before FAT,
//! `tos-api/src/bdos/process/pexec.rs`). U9 adds the one entry
//! `Embedded { name: "NEWDESK", file: "NEWDESK.NAP" }`.

use std::path::{Path, PathBuf};

/// One program the kernel image carries.
#[derive(Clone, Copy, Debug)]
pub struct Embedded {
    /// The registry name `Pexec` resolves it by (`registry::lookup`).
    pub name: &'static str,
    /// The program file `cargo xtask build-programs` writes into the board's
    /// directory ([`programs_dir`]).
    pub file: &'static str,
}

/// The programs embedded in every kernel image. Empty until DESK43 U9 (see
/// the module documentation).
pub const EMBEDDED: &[Embedded] = &[];

/// The directory `cargo xtask build-programs --board <board>` writes the
/// programs of one board into: `<workspace>/target/programs/<board>/`.
/// `board` is the board's name as the kernel's `BOARD_NAME` spells it
/// (`rpi4`, `qemu-virt`).
pub fn programs_dir(workspace: &Path, board: &str) -> PathBuf {
    workspace.join("target").join("programs").join(board)
}

/// The Rust source of `$OUT_DIR/embedded_programs.rs` for `list`, with every
/// file taken from `dir` — or, when one or more files are missing, the error
/// the kernel build stops with (naming every missing file and the command
/// that builds them).
///
/// The source defines
/// `pub static EMBEDDED_PROGRAMS: &[(&[u8], &[u8])]`, one
/// `(name, include_bytes!(<absolute path>))` per entry, in list order.
pub fn generate(list: &[Embedded], dir: &Path, board: &str) -> Result<String, String> {
    let missing: Vec<PathBuf> =
        list.iter().map(|e| dir.join(e.file)).filter(|p| !p.is_file()).collect();
    if !missing.is_empty() {
        let files: Vec<String> = missing.iter().map(|p| format!("  {}", p.display())).collect();
        return Err(format!(
            "kernel build: the kernel image embeds programs that have not been built for \
             board `{board}`:\n{}\nBuild them first: `cargo xtask build-programs --board {board}` \
             (`cargo xtask build` does this itself).",
            files.join("\n")
        ));
    }
    let mut s = String::new();
    s.push_str("// Generated by kernel/build.rs from kernel/embed.rs -- do not edit.\n");
    s.push_str(&format!("// Board `{board}`, programs from {}.\n", dir.display()));
    s.push_str("/// The programs embedded in this kernel image: (registry name, file image).\n");
    s.push_str("pub static EMBEDDED_PROGRAMS: &[(&[u8], &[u8])] = &[\n");
    for e in list {
        let path = dir.join(e.file);
        s.push_str(&format!("    (b{:?}, include_bytes!({:?})),\n", e.name, path.display().to_string()));
    }
    s.push_str("];\n");
    Ok(s)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("newtos-embed-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn board_directory_per_board() {
        let ws = Path::new("/ws");
        assert_eq!(programs_dir(ws, "rpi4"), Path::new("/ws/target/programs/rpi4"));
        assert_eq!(programs_dir(ws, "qemu-virt"), Path::new("/ws/target/programs/qemu-virt"));
    }

    #[test]
    fn empty_list_generates_an_empty_table() {
        let src = generate(&[], Path::new("/nonexistent"), "rpi4").unwrap();
        assert!(src.contains("pub static EMBEDDED_PROGRAMS: &[(&[u8], &[u8])] = &[\n];"), "{src}");
        assert!(!src.contains("include_bytes!"));
    }

    #[test]
    fn missing_blob_is_a_hard_error_naming_file_and_command() {
        let dir = scratch("missing");
        let list = [Embedded { name: "NEWDESK", file: "NEWDESK.NAP" }];
        let err = generate(&list, &dir, "qemu-virt").unwrap_err();
        assert!(err.contains(&dir.join("NEWDESK.NAP").display().to_string()), "{err}");
        assert!(err.contains("cargo xtask build-programs --board qemu-virt"), "{err}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn present_blob_is_included_by_absolute_path_under_its_name() {
        let dir = scratch("present");
        std::fs::write(dir.join("HELLOGEM.NAP"), b"\x7fELF").unwrap();
        let list = [Embedded { name: "HGEMBED", file: "HELLOGEM.NAP" }];
        let src = generate(&list, &dir, "rpi4").unwrap();
        let line = format!("    (b\"HGEMBED\", include_bytes!({:?})),\n", dir.join("HELLOGEM.NAP").display().to_string());
        assert!(src.contains(&line), "{src}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn one_missing_of_two_still_fails() {
        let dir = scratch("partial");
        std::fs::write(dir.join("A.NAP"), b"a").unwrap();
        let list = [Embedded { name: "A", file: "A.NAP" }, Embedded { name: "B", file: "B.NAP" }];
        let err = generate(&list, &dir, "rpi4").unwrap_err();
        assert!(err.contains("B.NAP") && !err.contains("A.NAP"), "{err}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// U6b state: nothing is embedded yet, and in particular no `NEWDESK` —
    /// the boot path is unchanged until U9 adds it.
    #[test]
    fn nothing_embedded_before_u9() {
        assert!(EMBEDDED.is_empty());
    }
}
