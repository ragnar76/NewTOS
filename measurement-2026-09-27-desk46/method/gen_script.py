#!/usr/bin/env python3
"""Generate the H02 injector SCRIPT (Rust) from a high-level action list.

usage: gen_script.py ACTIONS.txt CONST_NAME > script.rs
ACTIONS lines:  <tick> park | <tick> parkbr | <tick> move X Y | <tick> drag X Y |
                <tick> down | <tick> up | <tick> arm | <tick> mark NAME | <tick> pause |
                <tick> key HEXSCANCODE   (A87: one raw IKBD key byte, e.g. 62 = HELP make, E2 = break) |
                <tick> wheel DETENTS [LEN]  (GUI04: a synthesised USB boot-mouse report whose
                                             byte 3 carries DETENTS; LEN = report length in
                                             bytes, default 4. LEN 3 = a mouse WITHOUT a wheel,
                                             which must produce nothing.)
Absolute coordinates on the 640x480 screen; the generator tracks the pointer
and emits IKBD relative packets (|d| <= 127 per packet, one packet per tick).
`park` sweeps to (0,0) (top-left -- crosses the menu bar, see the A76
Nachtrag); `parkbr` (A79) sweeps to the bottom-right corner (639,479) instead,
which crosses no menu title.
"""
import sys
acts=[l.split() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
name=sys.argv[2] if len(sys.argv) > 2 else "SCRIPT"
px=py=None
out=[]
def emit(t, kind, dx=0, dy=0, name=""):
    out.append((t,kind,dx,dy,name))
for a in acts:
    t=int(a[0]); op=a[1]
    if op=='park':
        for k in range(6): emit(t+k,'mv',-127,-127)
        px=py=0
    elif op=='parkbr':
        for k in range(6): emit(t+k,'mv',127,127)
        px,py=639,479
    elif op=='move':
        x,y=int(a[2]),int(a[3]); dx,dy=x-px,y-py
        k=0
        while dx or dy:
            sx=max(-127,min(127,dx)); sy=max(-127,min(127,dy))
            emit(t+k,'mv',sx,sy); dx-=sx; dy-=sy; k+=1
        px,py=x,y
    elif op=='drag':
        x,y=int(a[2]),int(a[3]); dx,dy=x-px,y-py
        k=0
        while dx or dy:
            sx=max(-127,min(127,dx)); sy=max(-127,min(127,dy))
            emit(t+k,'dm',sx,sy); dx-=sx; dy-=sy; k+=1
        px,py=x,y
    elif op=='down': emit(t,'dn')
    elif op=='up': emit(t,'up')
    elif op=='arm': emit(t,'arm')
    elif op=='mark': emit(t,'mark',name=a[2])
    elif op=='pause': emit(t,'pause')
    elif op=='key': emit(t,'key',dx=int(a[2],16))
    elif op=='wheel': emit(t,'wheel',dx=int(a[2]),dy=int(a[3]) if len(a)>3 else 4)
print("    // generated by gen_script.py from", sys.argv[1])
print(f"    const {name}: &[(u32, Step)] = &[")
for t,kind,dx,dy,name_ in out:
    if kind=='mv': print(f"        ({t}, Step::Mv({dx}, {dy})),")
    elif kind=='dm': print(f"        ({t}, Step::Dm({dx}, {dy})),")
    elif kind=='dn': print(f"        ({t}, Step::Dn),")
    elif kind=='up': print(f"        ({t}, Step::Up),")
    elif kind=='arm': print(f"        ({t}, Step::Arm),")
    elif kind=='mark': print(f"        ({t}, Step::Mark(\"{name_}\")),")
    elif kind=='pause': print(f"        ({t}, Step::Pause),")
    elif kind=='key': print(f"        ({t}, Step::Key(0x{dx:02x})),")
    elif kind=='wheel': print(f"        ({t}, Step::Wheel({dx}, {dy})),")
print("    ];")
